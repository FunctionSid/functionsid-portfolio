function assertOracleIdentifier(value, label) {
  if (!/^[A-Z][A-Z0-9_]{0,127}$/.test(value)) {
    throw new Error(`Invalid Oracle identifier for ${label}.`);
  }
}

function quoteOraclePassword(password) {
  if (!password) {
    throw new Error('Oracle schema password is required.');
  }

  return `"${password.replace(/"/g, '""')}"`;
}

async function ensureApplicationSchema(connection, { schemaName, schemaPassword }, logger) {
  const normalizedSchema = schemaName.toUpperCase();
  assertOracleIdentifier(normalizedSchema, 'application schema');

  const quotedPassword = quoteOraclePassword(schemaPassword);

  try {
    await connection.execute(`CREATE USER ${normalizedSchema} IDENTIFIED BY ${quotedPassword}`);
    if (logger) {
      logger.info(`Oracle application schema ${normalizedSchema} created.`);
    }
  } catch (error) {
    if (error.errorNum !== 1920) {
      throw error;
    }

    await connection.execute(`ALTER USER ${normalizedSchema} IDENTIFIED BY ${quotedPassword} ACCOUNT UNLOCK`);
    if (logger) {
      logger.info(`Oracle application schema ${normalizedSchema} already exists and was synchronized.`);
    }
  }

  await connection.execute(`GRANT CREATE SESSION TO ${normalizedSchema}`);
  await connection.execute(`GRANT CREATE TABLE TO ${normalizedSchema}`);
  await connection.execute(`ALTER USER ${normalizedSchema} QUOTA 100M ON DATA`);
}

async function initializeSchema(connection, logger) {
  for (const statement of ddlStatements) {
    try {
      await connection.execute(statement);
    } catch (error) {
      if (error.errorNum !== 955) {
        throw error;
      }

      if (logger) {
        logger.debug('Oracle schema object already exists.');
      }
    }
  }
}

